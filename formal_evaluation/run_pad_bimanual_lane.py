#!/usr/bin/env python3
"""Run two complete PAD-Hand datasets serially on one assigned GPU."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from formal_evaluation.common.schema import validate_comparison_output
from formal_evaluation.datasets.window_inputs import load_window_input


def rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def verify_source(dataset: str, source: dict) -> list[dict]:
    expected = int(source["expected_windows"])
    gt = {row["window_id"]: row for row in rows(Path(source["gt_index"]))}
    inputs = rows(Path(source["input_index"]))
    if len(gt) != expected or len(inputs) != expected:
        raise ValueError(f"{dataset}: expected {expected} GT and input rows, got {len(gt)} and {len(inputs)}")
    selected = {}
    for item in inputs:
        path = Path(item["window_input"])
        record = load_window_input(path)
        key = record["window_id"]
        if record["dataset"] != dataset or key not in gt or key in selected:
            raise ValueError(f"{dataset}: duplicate, foreign or missing GT input {key}")
        if record["frame_ids"] != gt[key]["frame_ids"] or len(record["frame_ids"]) != 60:
            raise ValueError(f"{dataset}: frame identity mismatch {key}")
        mapping = json.loads((path.parent / "mapping.json").read_text())
        if mapping["window_id"] != key or mapping["frame_ids"] != record["frame_ids"]:
            raise ValueError(f"{dataset}: PAD mapping mismatch {key}")
        if (path.parent / "input.mp4").stat().st_size <= 0:
            raise ValueError(f"{dataset}: empty PAD input video {key}")
        selected[key] = {**record, "window_input": str(path)}
    if selected.keys() != gt.keys():
        raise ValueError(f"{dataset}: input/GT coverage mismatch")
    return [selected[key] for key in sorted(selected)]


def verify_output(path: Path, record: dict) -> list[int]:
    metadata = json.loads((path / "metadata.json").read_text())
    run = json.loads((path / "run.json").read_text())
    with np.load(path / "predictions.npz", allow_pickle=False) as payload:
        arrays = {name: payload[name] for name in payload.files}
    validate_comparison_output(metadata, arrays)
    if (metadata["method"], metadata["dataset"], metadata["window_id"], metadata["frame_ids"]) != (
        "pad_hand", record["dataset"], record["window_id"], record["frame_ids"]
    ) or run.get("status") != "success":
        raise ValueError(f"PAD output identity/status mismatch: {path}")
    if arrays["hand_vertices_camera"].shape != (60, 2, 778, 3) or arrays["hand_valid"].shape != (60, 2):
        raise ValueError(f"PAD dual-hand output shape mismatch: {path}")
    if metadata.get("hand_tracks") != "independent_left_right_refinement":
        raise ValueError(f"PAD output was not generated by the dual-hand adapter: {path}")
    return arrays["hand_valid"].sum(axis=0).astype(int).tolist()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", required=True, type=Path)
    parser.add_argument("--output-root", required=True, type=Path)
    parser.add_argument("--pilot", action="store_true", help="run one selected window from the first dataset")
    args = parser.parse_args()
    spec = json.loads(args.spec.read_text())
    datasets = spec["datasets"]
    if len(datasets) != (1 if args.pilot else 2):
        raise ValueError("pilot requires one dataset; a full lane requires exactly two")
    if not os.environ.get("CUDA_VISIBLE_DEVICES"):
        raise ValueError("CUDA_VISIBLE_DEVICES must name the assigned physical GPU")
    root = args.output_root
    root.mkdir(parents=True, exist_ok=True)
    if (root / "COMPLETE").exists():
        raise FileExistsError(f"lane already complete: {root}")
    prepared = {dataset: verify_source(dataset, source) for dataset, source in datasets.items()}
    for dataset, records in prepared.items():
        if args.pilot:
            records = records[:1]
        result_path = root / dataset / "progress.jsonl"
        result_path.parent.mkdir(parents=True, exist_ok=True)
        if result_path.exists():
            raise FileExistsError(f"refusing implicit partial rerun: {result_path}")
        start = time.monotonic()
        valid_counts = [0, 0]
        with result_path.open("x") as progress:
            for index, record in enumerate(records, 1):
                command = [spec["runtime"]["python"], "-m",
                    "formal_evaluation.hand.adapters.run_pad_hand_baseline",
                    "--phase", "pilot" if args.pilot else "formal",
                    "--window-input", record["window_input"],
                    "--methods-config", spec["methods_config"],
                    "--source-root", spec["runtime"]["source_root"],
                    "--wilor-python", spec["runtime"]["wilor_python"],
                    "--checkpoint", spec["runtime"]["checkpoint"],
                    "--output-root", str(root / dataset)]
                environment = {**os.environ, "OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1",
                    "MKL_NUM_THREADS": "1", "PYTHONPATH": spec["code_root"]}
                subprocess.run(command, env=environment, check=True)
                output = root / dataset / "pad_hand" / ("pilot" if args.pilot else "formal") / record["cache_id"]
                counts = verify_output(output, record)
                valid_counts = [valid_counts[side] + counts[side] for side in range(2)]
                progress.write(json.dumps({"window_id": record["window_id"], "cache_id": record["cache_id"],
                                           "prediction_dir": str(output), "valid_side_frames": counts}) + "\n")
                progress.flush()
                print(json.dumps({"dataset": dataset, "completed": index, "target": len(records),
                                  "valid_side_frames": counts}), flush=True)
        summary = {"status": "complete", "dataset": dataset, "completed_windows": len(records),
                   "valid_side_frames": valid_counts, "elapsed_seconds": time.monotonic() - start}
        (root / dataset / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    lane = {"status": "complete", "datasets": list(datasets), "pilot": args.pilot,
            "completed_windows": sum(1 if args.pilot else source["expected_windows"] for source in datasets.values())}
    (root / "summary.json").write_text(json.dumps(lane, indent=2) + "\n")
    (root / "COMPLETE").write_text("complete\n")


if __name__ == "__main__":
    main()
